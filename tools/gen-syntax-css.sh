#!/usr/bin/env bash
# Regenerate static/css/syntax.css from the default Emacs light theme.
set -e

RAW="$(mktemp)"
trap 'rm -f "$RAW"' EXIT

SYNTAX_CSS_OUT="$RAW" emacs -q -l tools/gen-syntax-css.el

# Keep only the .org-* rules that set something. Drop backgrounds so tokens
# sit on the code block background.
{
  echo "/* Generated by tools/gen-syntax-css.sh from the default Emacs theme. */"
  awk '
    /^ *\.org-[a-z0-9-]+ \{$/ { sel = $1; body = ""; inrule = 1; next }
    inrule && /^ *\}$/ {
      if (body != "") printf "%s {\n%s}\n", sel, body
      inrule = 0; next
    }
    inrule && /background-color/ { next }
    inrule && /:/ { sub(/^ */, "  "); body = body $0 "\n" }
  ' "$RAW"
} > static/css/syntax.css
